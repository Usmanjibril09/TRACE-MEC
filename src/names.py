"""Display-name registry: load, validate against result files, emit LaTeX macros."""
import sys, pathlib as P, yaml, pyarrow.parquet as pq, pyarrow.compute as pc
ROOT = P.Path(__file__).resolve().parents[1]
REG = yaml.safe_load(open(ROOT / "config/names.yaml"))
def name(kind, code, form="short"):
    try: return REG[kind][code][form]
    except KeyError: raise SystemExit(f"STOP: '{code}' missing from names.yaml [{kind}] - add it, do not fall back to the code")
def validate():
    seen = {"method": set(), "profile": set(), "variant": set()}; n = 0
    for f in sorted(ROOT.glob("results/**/episodes_*.parquet")):
        cols = [c for c in seen if c in pq.read_schema(f).names]
        t = pq.read_table(f, columns=cols); n += 1
        for c in cols: seen[c] |= set(pc.unique(t[c]).to_pylist())
    kinds = {"method": "methods", "profile": "profiles", "variant": "variants"}
    miss = {c: sorted(v - set(REG[kinds[c]])) for c, v in seen.items()}
    unused = {c: sorted(set(REG[kinds[c]]) - v) for c, v in seen.items()}
    print(f"scanned {n} episodes files"); print("codes found:", {c: len(v) for c, v in seen.items()})
    print("MISSING from registry:", miss); print("in registry but never in results:", unused)
    return not any(miss.values())
def tex():
    L = ["% auto-generated by src/names.py from config/names.yaml - do not edit", r"\usepackage{xspace}"]
    for code, d in {**REG["methods"], **REG["terms"]}.items():
        if d.get("report") == "excluded": continue
        L.append(rf"\newcommand{{\{d['macro']}}}{{{d['short']}\xspace}}  % {code}")
    (ROOT / "docs/names.tex").write_text("\n".join(L) + "\n"); print("wrote docs/names.tex")
if __name__ == "__main__":
    ok = validate(); tex(); print("REGISTRY CHECK:", "PASS" if ok else "FAIL"); sys.exit(0 if ok else 1)
